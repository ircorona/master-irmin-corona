/**
 * Check if an IP falls within a CIDR range or matches an exact IP.
 * Supports IPv4 and IPv6.
 */
function ip_in_range(string $ip, string $range): bool {
    // Exact match (no CIDR notation, e.g. "127.0.0.1")
    if (strpos($range, '/') === false) {
        return $ip === $range;
    }

    [$subnet, $bits] = explode('/', $range, 2);
    $bits = (int) $bits;

    $ip_bin     = @inet_pton($ip);
    $subnet_bin = @inet_pton($subnet);
    if ($ip_bin === false || $subnet_bin === false) {
        return false;
    }
    if (strlen($ip_bin) !== strlen($subnet_bin)) {
        return false;  // Mismatched address families (IPv4 vs IPv6)
    }

    $bytes     = intdiv($bits, 8);
    $remainder = $bits % 8;

    if (substr($ip_bin, 0, $bytes) !== substr($subnet_bin, 0, $bytes)) {
        return false;
    }
    if ($remainder === 0) {
        return true;
    }
    $mask = chr((0xFF << (8 - $remainder)) & 0xFF);
    return (ord($ip_bin[$bytes]) & ord($mask)) === (ord($subnet_bin[$bytes]) & ord($mask));
}

function ip_in_any_range(string $ip, array $ranges): bool {
    foreach ($ranges as $range) {
        if (ip_in_range($ip, $range)) {
            return true;
        }
    }
    return false;
}

